extensions.configure<ApplicationExtension> {
    namespace = "com.asterixorobelix.remit.app"
    compileSdk =
        libs.versions.android.compileSdk
            .get()
            .toInt()

    defaultConfig {
        applicationId = appProperties.getProperty("PACKAGE_NAME")
        minSdk =
            libs.versions.android.minSdk
                .get()
                .toInt()
        targetSdk =
            libs.versions.android.targetSdk
                .get()
                .toInt()
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        versionCode = appProperties.getProperty("VERSION_CODE").toInt()
        versionName = appProperties.getProperty("VERSION_NAME")
        // Without google-services.json there is no project to report to: switch Analytics off
        // entirely so it does not start its measurement service (see AndroidManifest.xml).
        manifestPlaceholders["firebaseAnalyticsDeactivated"] = (!firebaseEnabled).toString()

        // What AndroidAppConfig hands the shared code. These are the production values; debug and
        // staging override them, and build types made from release (the baseline profile's) keep them.
        buildConfigField("String", "RELEASE_APPLICATION_ID", "\"${appProperty("PACKAGE_NAME")}\"")
        buildConfigField("String", "CAPABILITIES", "\"${appProperty("FEATURES")}\"")
        buildConfigField("String", "ENVIRONMENT", "\"production\"")
        buildConfigField("String", "API_BASE_URL", "\"${appProperty("API_BASE_URL_RELEASE")}\"")
        buildConfigField("String", "FIREBASE_EMULATOR_HOST", "\"\"")
        buildConfigField("boolean", "ANALYTICS_ENABLED", "true")
        buildConfigField("boolean", "CRASH_REPORTING_ENABLED", "true")
    }

    buildFeatures {
        buildConfig = true
    }

    // Release signing configuration - optional until keystore is provided
    val keystorePropertiesFile = rootProject.file("keystore.properties")
    val hasKeystore = keystorePropertiesFile.exists() || System.getenv("KEYSTORE_FILE") != null

    if (hasKeystore) {
        signingConfigs {
            create("release") {
                if (keystorePropertiesFile.exists()) {
                    val keystoreProperties = Properties()
                    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
                    storeFile = file(keystoreProperties["storeFile"].toString())
                    storePassword = keystoreProperties["storePassword"].toString()
                    keyAlias = keystoreProperties["keyAlias"].toString()
                    keyPassword = keystoreProperties["keyPassword"].toString()
                } else {
                    // CI/CD environment variables
                    storeFile = file(System.getenv("KEYSTORE_FILE")!!)
                    storePassword = System.getenv("KEYSTORE_PASSWORD") ?: ""
                    keyAlias = System.getenv("KEY_ALIAS") ?: ""
                    keyPassword = System.getenv("KEY_PASSWORD") ?: ""
                }
            }
        }
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
        jniLibs {
            useLegacyPackaging = false
            keepDebugSymbols += "**/*.so"
        }
    }

    buildTypes {
        getByName("debug") {
            applicationIdSuffix = ".debug"
            isDebuggable = true
            isMinifyEnabled = false
            buildConfigField("String", "ENVIRONMENT", "\"development\"")
            buildConfigField("String", "API_BASE_URL", "\"${appProperty("API_BASE_URL_DEBUG")}\"")
            // Debug only: points Auth and Firestore at the local Firebase Emulator Suite.
            buildConfigField("String", "FIREBASE_EMULATOR_HOST", "\"$firebaseEmulatorHost\"")
            buildConfigField("boolean", "ANALYTICS_ENABLED", "false")
            buildConfigField("boolean", "CRASH_REPORTING_ENABLED", "false")
        }
        getByName("release") {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            if (hasKeystore) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    // Every minified build type (release, and the baseline profile's benchmark builds) gets a mapping
    // upload task; uploading needs the project's google_app_id, which only google-services.json has.
    buildTypes.configureEach {
        (this as ExtensionAware).configure<CrashlyticsExtension> { mappingFileUploadEnabled = firebaseEnabled }
    }

    // Staging build type (optional)
    buildTypes.create("staging") {
        initWith(buildTypes.getByName("debug"))
        applicationIdSuffix = ".staging"
        buildConfigField("String", "ENVIRONMENT", "\"staging\"")
        buildConfigField("String", "API_BASE_URL", "\"${appProperty("API_BASE_URL_STAGING")}\"")
        buildConfigField("String", "FIREBASE_EMULATOR_HOST", "\"\"")
        buildConfigField("boolean", "ANALYTICS_ENABLED", "true")
        buildConfigField("boolean", "CRASH_REPORTING_ENABLED", "true")
    }

    compileOptions {
        val javaVersion = JavaVersion.toVersion(libs.versions.android.jvmTarget.get())
        sourceCompatibility = javaVersion
        targetCompatibility = javaVersion
    }

    // Android Lint gate: `:androidApp:lintDebug` (debug only; release builds still run lintVital).
    // Pre-existing findings live in the committed lint-baseline.xml; anything new fails the task,
    // warnings included. Refresh the baseline with `:androidApp:updateLintBaseline` only for
    // findings you have decided to accept.
    lint {
        baseline = file("lint-baseline.xml")
        abortOnError = true
        warningsAsErrors = true
        checkReleaseBuilds = true
        disable +=
            setOf(
                // Version-freshness checks depend on the day the build runs, not on the change;
                // dependency updates are handled separately (version catalog + `check deps`).
                "AndroidGradlePluginVersion",
                "GradleDependency",
                "NewerVersionAvailable",
                "OldTargetApi",
            )
    }
}

