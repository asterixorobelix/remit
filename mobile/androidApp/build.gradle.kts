// Strings that only appear in the placeholder google-services.json of older template versions.
val firebasePlaceholderMarkers = listOf("DEFAULT TEMPLATE", "your-project-id-here")

// Firebase is configured from a real google-services.json next to this file (it is gitignored; CI
// writes it from the GOOGLE_SERVICES_JSON secret) when `firebase` is in FEATURES (app.properties).
// Without it, debug builds can use the emulators and release builds run without Firebase: the
// SDKs are linked but never started, so crash reports and analytics stay in logcat.
val firebaseCapability = appProperties.getProperty("FEATURES").orEmpty()
    .split(',')
    .any { it.trim().equals("firebase", ignoreCase = true) }
val googleServicesFile = file("google-services.json")
val hasRealGoogleServices = googleServicesFile.exists() &&
    googleServicesFile.readText().let { json ->
        firebasePlaceholderMarkers.none { marker -> json.contains(marker) }
    }
val firebaseEnabled = firebaseCapability && hasRealGoogleServices

// Without google-services.json, debug builds use the local Firebase Emulator Suite (`make emulators`)
// at 10.0.2.2, the host as seen from the Android emulator (BuildConfig.FIREBASE_EMULATOR_HOST below).
// FIREBASE_EMULATOR_HOST in local.properties or the environment overrides it: localhost on a device
// with `adb reverse`, or blank for a debug build without Firebase.
val firebaseEmulatorHost =
    localProperties.getProperty("FIREBASE_EMULATOR_HOST")
        ?: System.getenv("FIREBASE_EMULATOR_HOST")
        ?: if (firebaseCapability && !hasRealGoogleServices) "10.0.2.2" else ""
if (firebaseCapability && !hasRealGoogleServices) {
    if (firebaseEmulatorHost.isBlank()) {
        logger.warn(
            "WARNING: FIREBASE_EMULATOR_HOST is blank and there is no androidApp/google-services.json, " +
                "so Send and History fail in the debug app. Remove the blank setting to use the emulators " +
                "(see \"Run it\" in README.md).",
        )
    } else {
        logger.info(
            "No androidApp/google-services.json: debug builds use the Firebase emulators at " +
                "$firebaseEmulatorHost; release builds have no Firebase.",
        )
    }
}
if (firebaseEnabled) {
    apply(plugin = "com.google.gms.google-services")
}

